#!/usr/bin/env python3
"""Merge per-step summary JSONs + run parameters into report_data.json
and render a self-describing Markdown report (report.md) for Quarto."""

import json
import os
import shutil
from datetime import datetime, timezone

FIGURES = "${figures}".split()
SUMMARIES = "${summaries}".split()
PARAMS_FILE = "${params_file}"

os.makedirs("figures", exist_ok=True)
for _f in FIGURES:
    shutil.copy(_f, "figures/")

summaries = SUMMARIES
params_file = PARAMS_FILE

samples = {}
for path in summaries:
    try:
        with open(path) as fh:
            s = json.load(fh)
    except Exception as exc:  # noqa: BLE001
        print(f"WARNING: unreadable summary {path}: {exc}")
        continue
    sid = s.get("sample", "unknown")
    samples.setdefault(sid, {"id": sid, "summaries": [], "figures": []})
    samples[sid]["summaries"].append(s)

with open(params_file) as fh:
    params = json.load(fh)

# Attribute figures to samples by filename prefix
figdir = "figures"
for fname in sorted(os.listdir(figdir)):
    if not fname.endswith((".pdf", ".png")):
        continue
    matched = None
    for sid in samples:
        if fname.startswith(sid + "_") or fname.startswith(sid + "-"):
            matched = sid
            break
    if matched is None and samples:
        matched = next(iter(samples))
    if matched:
        samples[matched]["figures"].append(fname)

run = {
    "pipeline": "nf-xen",
    "nextflow_version": os.environ.get("NXF_VER", "see log"),
    "generated": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
}
with open("report_data.json", "w") as fh:
    json.dump({"run": run, "params": params, "samples": list(samples.values())}, fh, indent=2)


# ------------------------------------------------------------------ markdown
def fmt(v):
    if v is None or v == "":
        return "—"
    if isinstance(v, (dict, list)):
        return json.dumps(v)
    if isinstance(v, float):
        return f"{v:.4g}"
    return str(v)


def md_table(obj, skip=()):
    rows = [(k, v) for k, v in obj.items() if k not in skip]
    if not rows:
        return "_no metrics_"
    out = ["| Metric | Value |", "|---|---|"]
    out += [f"| `{k}` | {fmt(v)} |" for k, v in rows]
    return "\\n".join(out)


lines = [
    "---",
    'title: "nf-xen — Xenium analysis report"',
    "format:",
    "  html:",
    "    toc-depth: 3",
    "    number-sections: true",
    "    self-contained: true",
    "---",
    "",
    "## Run overview",
    "",
    md_table(run),
    "",
    "### Pipeline parameters",
    "",
    md_table(params),
    "",
]

for s in samples.values():
    lines += ["---", "", f"# Sample: `{s['id']}`", "", "## Step results", ""]
    if not s["summaries"]:
        lines += ["_no step summaries_", ""]
    for sum_ in s["summaries"]:
        lines += [f"## {sum_.get('step', 'summary')}", "",
                  md_table(sum_, skip=("sample", "step")), ""]
    lines += ["## Figures", ""]
    if not s["figures"]:
        lines += ["_No figures were produced for this sample._", ""]
    for f in s["figures"]:
        if f.endswith(".png"):
            media = [
                f'  <img src="figures/{f}" alt="{f}" style="max-width:100%; height:auto;">',
            ]
        else:
            media = [
                f'  <object data="figures/{f}" type="application/pdf" width="100%" height="700px">',
                f'    <a href="figures/{f}">Download {f}</a>',
                f'  </object>',
            ]
        lines += [
            f'<figure>',
            *media,
            f'  <figcaption>{f}</figcaption>',
            f'</figure>',
            "",
        ]

lines += ["---", "",
          "*Report generated by nf-xen. Figures are embedded as PDF objects — "
          "most browsers render them inline.*", ""]

with open("report.md", "w") as fh:
    fh.write("\\n".join(lines))

print(f"report_data.json + report.md written: {len(samples)} sample(s)")
